// Array of all products
export const ALL_PRODUCTS_LIST = Object.values(ALL_PRODUCTS);

// Lookup helpers
export function getProductById(id: string): ProductItem | undefined {
  return ALL_PRODUCTS[id];
}

export function getProductBySlug(slug: string): ProductItem | undefined {
  return ALL_PRODUCTS_LIST.find(p => p.slug.toLowerCase() === slug.toLowerCase());
}

export function getProductBySlugOrId(identifier: string): ProductItem | undefined {
  const decoded = decodeURIComponent(identifier).trim().toLowerCase();
  // 1. Direct ID lookup
  if (ALL_PRODUCTS[decoded]) return ALL_PRODUCTS[decoded];
  // 2. Slug match
  const bySlug = ALL_PRODUCTS_LIST.find(p => p.slug.toLowerCase() === decoded);
  if (bySlug) return bySlug;
  // 3. Normalized ID match
  const byId = ALL_PRODUCTS_LIST.find(p => p.id.toLowerCase() === decoded);
  if (byId) return byId;
  // 4. Name match fallback
  const byName = ALL_PRODUCTS_LIST.find(p => p.name.toLowerCase().replace(/\s+/g, '-') === decoded);
  if (byName) return byName;
  return undefined;
}

// Reusable Related Add-ons Recommendation Engine
export function getRelatedAddOns(product: ProductItem, limit: number = 5): ProductItem[] {
  const results: ProductItem[] = [];
  const addedIds = new Set<string>([product.id]);

  // 1. Explicit Add-On relationships if defined
  if (product.addOnIds && product.addOnIds.length > 0) {
    for (const addOnId of product.addOnIds) {
      if (!addedIds.has(addOnId) && ALL_PRODUCTS[addOnId]) {
        results.push(ALL_PRODUCTS[addOnId]);
        addedIds.add(addOnId);
        if (results.length >= limit) return results;
      }
    }
  }

  // 2. Compatible accessory category classification
  const isCamera = product.category.includes('camera') || product.category === 'dji-cameras';
  const isOutdoor = product.category.includes('trekking') || product.category.includes('camping') || product.category.includes('winter');
  const isRiding = product.category.includes('riding');

  if (isCamera) {
    const cameraAddOnIds = ['ta-9', 'bat-new-2', 'wm-2', 'ta-2', 'acm-1', 'acm-15', 'ta-12', 'bat-new-1', 'acm-6'];
    for (const id of cameraAddOnIds) {
      if (!addedIds.has(id) && ALL_PRODUCTS[id]) {
        results.push(ALL_PRODUCTS[id]);
        addedIds.add(id);
        if (results.length >= limit) return results;
      }
    }
  } else if (isRiding) {
    const ridingAddOnIds = ['rg-4', 'rg-5', 'rg-3', 'rg-7', 'rl-2', 'rl-1', 'acm-14'];
    for (const id of ridingAddOnIds) {
      if (!addedIds.has(id) && ALL_PRODUCTS[id]) {
        results.push(ALL_PRODUCTS[id]);
        addedIds.add(id);
        if (results.length >= limit) return results;
      }
    }
  } else if (isOutdoor) {
    const outdoorAddOnIds = ['tg-6', 'tg-9', 'bp-1', 'tg-1', 'tg-3', 'cg-3', 'cg-5', 'cg-8', 'tg-11'];
    for (const id of outdoorAddOnIds) {
      if (!addedIds.has(id) && ALL_PRODUCTS[id]) {
        results.push(ALL_PRODUCTS[id]);
        addedIds.add(id);
        if (results.length >= limit) return results;
      }
    }
  }

  // 3. Same category / accessories fallback
  for (const item of ALL_PRODUCTS_LIST) {
    if (!addedIds.has(item.id) && item.id !== product.id) {
      results.push(item);
      addedIds.add(item.id);
      if (results.length >= limit) break;
    }
  }

  return results;
}

// Category-Aware Related Add-ons Navigation Target
export function getRelatedAddOnsCategory(product: ProductItem): { key: string; label: string } {
  const cat = (product.category || '').toLowerCase();
  
  // Photography products navigate to ACTION CAMERA ADD ONS
  const isPhotography = 
    cat.includes('camera') || 
    cat.includes('photo') || 
    cat === 'dji-cameras' || 
    cat === 'gimbals' || 
    cat === 'mobile-gimbals' || 
    cat === 'wireless-mics' || 
    cat === 'tripod-accessories' ||
    cat === 'action-camera-add-ons';

  if (isPhotography) {
    return { key: 'action-camera-add-ons', label: 'ACTION CAMERA ADD ONS' };
  }

  // Outdoor subcategory mapping
  if (cat === 'camping-gear') {
    return { key: 'camping-gear', label: 'CAMPING ADD ONS' };
  }
  if (cat === 'riding-gear' || cat === 'riding-luggage') {
    return { key: 'riding-gear', label: 'RIDING GEAR & ACCESSORIES' };
  }
  if (cat === 'winter-jackets') {
    return { key: 'winter-jackets', label: 'WINTER GEAR' };
  }
  if (cat === 'backpacks' || cat === 'trekking-gear') {
    return { key: 'trekking-gear', label: 'TREKKING ACCESSORIES' };
  }

  return { key: 'outdoor', label: 'OUTDOOR GEAR' };
}

// Helper to get formatted Brand label
export function getProductBrand(product: ProductItem): string {
  if (product.brand) return product.brand;
  const name = product.name.toLowerCase();
  if (name.includes('dji')) return 'DJI';
  if (name.includes('insta 360') || name.includes('insta360')) return 'INSTA360';
  if (name.includes('gopro') || name.includes('gp ')) return 'GOPRO';
  if (name.includes('sony')) return 'SONY';
  if (name.includes('canon')) return 'CANON';
  if (name.includes('rode')) return 'RODE';
  if (name.includes('sandisk')) return 'SANDISK';
  if (name.includes('viaterra')) return 'VIATERRA';
  if (name.includes('axor')) return 'AXOR';
  if (product.categoryName) return product.categoryName.toUpperCase();
  return 'GEAR';
}
